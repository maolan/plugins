#[derive(Debug, Clone, Copy)]
pub struct ParamDef {
    pub id: ParamId,
    pub name: &'static str,
    pub module: &'static str,
    pub min: f64,
    pub max: f64,
    pub default: f64,
    pub step: f64,
    pub flags: u32,
}

const AUTOMATABLE: u32 = CLAP_PARAM_IS_AUTOMATABLE | CLAP_PARAM_REQUIRES_PROCESS;
const ENUM: u32 = CLAP_PARAM_IS_ENUM
    | CLAP_PARAM_IS_STEPPED
    | CLAP_PARAM_IS_AUTOMATABLE
    | CLAP_PARAM_REQUIRES_PROCESS;
const TOGGLE: u32 = CLAP_PARAM_IS_STEPPED | CLAP_PARAM_IS_AUTOMATABLE | CLAP_PARAM_REQUIRES_PROCESS;
#[allow(dead_code)]
const STEPPED: u32 = CLAP_PARAM_IS_STEPPED | CLAP_PARAM_IS_AUTOMATABLE | CLAP_PARAM_REQUIRES_PROCESS;

macro_rules! def_automatable {
    ($id:expr, $name:expr, $module:expr, $min:expr, $max:expr, $default:expr, $step:expr) => {
        ParamDef {
            id: $id,
            name: $name,
            module: $module,
            min: $min,
            max: $max,
            default: $default,
            step: $step,
            flags: AUTOMATABLE,
        }
    };
}

